// ---------- Топ (жас тобы) анықтау көмекшілері ----------
export const GROUP_DEFS = [
  { id: "kishi", label: "Кіші топ - Байтерек ", order: 1, re: /кіші|байтерек/i },
  { id: "orta", label: "Ортаңғы топ - Балапан ", order: 2, re: /ортаңғы|балапан|балшекер/i },
  { id: "ulken", label: "Үлкен топ - Күншуақ", order: 3, re: /ересек|күншуақ/i },
  { id: "ma", label: "МА топ - Болашақ ", order: 4, re: /болашақ|мектепалды|мад|(^|[^a-zа-яёіңғүұқөһ])ма([^a-zа-яёіңғүұқөһ]|$)/i },
];

export function detectGroup(name) {
  for (const g of GROUP_DEFS) {
    if (g.re.test(name)) return g;
  }
  return null;
}

function detectGroupOrder(name) {
  const g = detectGroup(name);
  return g ? g.order : 9;
}

// ---------- Оқу жылын нақты анықтау функциясы ----------
export function detectYear(name) {
  if (!name || typeof name !== 'string') return null;

  // 1. Оқу жылы форматын тексеру (мысалы: "2023-2024" немесе "23-24")
  // y2 әрқашан y1 + 1 болуы керек (мысалы: 2025-2026)
  const rangeMatch = name.match(/\b(20\d{2}|\d{2})\s*[-–]\s*(20\d{2}|\d{2})\b/);
  if (rangeMatch) {
    let y1 = parseInt(rangeMatch[1], 10);
    let y2 = parseInt(rangeMatch[2], 10);
    y1 = y1 < 100 ? 2000 + y1 : y1;
    y2 = y2 < 100 ? Math.floor(y1 / 100) * 100 + y2 : y2;

    if (y2 === y1 + 1 && y1 >= 2020 && y1 <= 2030) {
      return { year: y1, label: `${y1}-${y2}` };
    }
  }

  // Күн форматындағы сандарды (05.08.2026, 2026.5.19, 2026-08-22 т.б.) өткізіп жіберу
  if (/\b\d{1,4}[-./]\d{1,2}[-./]\d{1,4}\b/.test(name)) {
    return null;
  }

  // 2. Жалғыз жыл форматын тексеру (мысалы: "2024", "2025", "2026")
  // \b шекарасы ИИН немесе ұзын ID ішіндегі сандарды қабылдаудан қорғайды
  const singleMatch = name.match(/\b(20[2-3]\d)\b/);
  if (singleMatch) {
    const y = parseInt(singleMatch[0], 10);
    if (y >= 2020 && y <= 2030) {
      return { year: y, label: `${y}` };
    }
  }

  return null;
}

function extractYear(name) {
  const d = detectYear(name);
  return d ? d.year : 0;
}

const collator = new Intl.Collator("kk", { sensitivity: "base", numeric: true });

function sortFiles(files) {
  return [...new Set(files)].sort((a, b) => {
    const ga = detectGroupOrder(a);
    const gb = detectGroupOrder(b);
    if (ga !== gb) return ga - gb;
    const ya = extractYear(a);
    const yb = extractYear(b);
    if (ya !== yb) return ya - yb;
    return collator.compare(a, b);
  });
}

