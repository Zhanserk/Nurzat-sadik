// Бұл функциялар екі жерде қолданылады:
//  1) sortFiles() ішінде — карточка ішіндегі файлдарды топ пен жыл бойынша реттеу үшін.
//  2) FilesPage.jsx ішінде — "Топ" және "Жыл" сүзгілері үшін (барлық құжаттарға қолданылады).

export const GROUP_DEFS = [
  { id: "kishi", label: "Кіші топ - Байтерек ", order: 1, re: /кіші|байтерек/i },
  { id: "orta", label: "Ортаңғы топ - Балапан ", order: 2, re: /ортаңғы|балапан|балшекер/i },
  { id: "ulken", label: "Үлкен топ - Күншуақ", order: 3, re: /ересек|күншуақ/i },
  { id: "ma", label: "МА топ - Болашақ ", order: 4, re: /болашақ|мектепалды|(^|[^a-zа-яёіңғүұқөһ])ма([^a-zа-яёіңғүұқөһ]|$)/i },
];

// Файл атауынан топты анықтайды. Табылмаса — null (яғни бұл жалпы,
// топқа тән емес құжат: жылдық жоспар, хаттама, сертификат, т.б.
// Мұндай құжаттар қай топ таңдалса да көрініп тұруы керек, өйткені
// олар бүкіл балабақшаға қатысты).
export function detectGroup(name) {
  for (const g of GROUP_DEFS) {
    if (g.re.test(name)) return g;
  }
  return null;
}

function detectGroupOrder(name) {
  const g = detectGroup(name);
  return g ? g.order : 9;
}

// Файл атауынан оқу жылын анықтайды. Мыс: "23-24" -> {year:2023, label:"2023-2024"},
// "2025-2026" -> {year:2025, label:"2025-2026"}, "2024" -> {year:2024, label:"2024"}.
// Табылмаса — null.
export function detectYear(name) {
  let m = name.match(/(\d{2,4})\s*[-–]\s*(\d{2,4})/);
  if (m) {
    let y1 = parseInt(m[1], 10);
    let y2 = parseInt(m[2], 10);
    y1 = y1 < 100 ? 2000 + y1 : y1;
    y2 = y2 < 100 ? Math.floor(y1 / 100) * 100 + y2 : y2;
    return { year: y1, label: `${y1}-${y2}` };
  }
  m = name.match(/20\d{2}/);
  if (m) {
    const y = parseInt(m[0], 10);
    return { year: y, label: `${y}` };
  }
  m = name.match(/\b(2[3-9])\b/);
  if (m) {
    const y = 2000 + parseInt(m[1], 10);
    return { year: y, label: `${y}` };
  }
  return null;
}

function extractYear(name) {
  const d = detectYear(name);
  return d ? d.year : 0;
}

const collator = new Intl.Collator("kk", { sensitivity: "base", numeric: true });

function sortFiles(files) {
  return [...new Set(files)].sort((a, b) => {
    const ga = detectGroupOrder(a);
    const gb = detectGroupOrder(b);
    if (ga !== gb) return ga - gb;
    const ya = extractYear(a);
    const yb = extractYear(b);
    if (ya !== yb) return ya - yb;
    return collator.compare(a, b);
  });
}

